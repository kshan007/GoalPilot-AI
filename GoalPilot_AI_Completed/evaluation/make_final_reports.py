def render(df: pd.DataFrame, spec, index=False) -> str:
    """spec: list of (column, header, format-string)."""
    lines = ["| " + " | ".join(h for _, h, _ in spec) + " |",
             "|" + "|".join("---" for _ in spec) + "|"]
    for _, row in df.iterrows():
        cells = []
        for column, _, fmt in spec:
            value = row[column] if column in df.columns else None
            if value is None or (isinstance(value, float) and pd.isna(value)):
                cells.append("n/a")
            elif isinstance(value, str):
                cells.append(value)
            else:
                cells.append(fmt.format(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def load(name: str, directory: Path = EVAL_OUT) -> pd.DataFrame:
    path = directory / name
    if not path.is_file():
        raise FileNotFoundError(path)
    return pd.read_csv(path)


